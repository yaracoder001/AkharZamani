const NAV = { next: "صفحه بعد ◀️", prev: "▶️ صفحه قبل" };

// برچسب دکمه (با ایموجی) ← نام تمیز بدون ایموجی
const LABELS = new Map();
const reg = (s) => LABELS.set(T.norm(s), T.noEmoji(s) || T.norm(s));
for (const v of Object.values(M))
  for (const row of v) for (const b of row) reg(b);
reg(NAV.next);
reg(NAV.prev);

// متنی که کاربر فرستاده را به نام تمیز دکمه تبدیل می‌کند؛ اگر دکمه نبود همان متن برمی‌گردد
M.resolve = (text) => {
  const n = T.norm(text);
  return LABELS.get(n) || n;
};
M.NAV = NAV;

