const flagOf = (name) => {
  const code = ISO[String(name || '').trim()];
  return code ? String.fromCodePoint(...[...code].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65)) : '';
};
// «🇮🇷 ایران»
const withFlag = (name) => {
  const f = flagOf(name);
  return f ? f + ' ' + name : String(name || '');
};

